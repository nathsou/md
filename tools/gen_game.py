"""Recompiles a game: every program module in its exefs (main, subsdk0-9, sdk) to C, in parallel.

usage: gen_game.py <game dir (exefs/, romfs/)> <output dir> [--simd asm|c] [-j N]

Module layout: the modules are placed one after another from MAIN_BASE (runtime/rt.h) in Horizon's load order (main,
subsdk0..9, sdk; rtld is the runtime's own), each at a 16 MB boundary with at least 16 MB free after the one before,
and must end below HLE_BASE. The generated code has its addresses built in, so the layout is part of it: the runtime
takes each module's base from the game code library (gamelib_modules.c here, runtime/gamelib.h).

Writes <output dir>/<module>/*.c (tools/gen.py), gamelib_modules.c, main_build_id.txt (the library's id: a library
for other game files is never loaded) and game.txt (the profile, or none).
"""
import argparse
import os
import platform
import re
import subprocess
import sys
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import games  # noqa: E402
from nso import Nso  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
ORDER = ['main'] + [f'subsdk{i}' for i in range(10)] + ['sdk']
ALIGN = 0x1000000


def rt_const(name):
    m = re.search(rf'^#define {name}\s+(0x[0-9a-fA-F]+)', (ROOT / 'runtime/rt.h').read_text(), re.M)
    if not m:
        sys.exit(f'runtime/rt.h: no {name}')
    return int(m[1], 16)


def layout(exefs):
    base, hi = rt_const('MAIN_BASE'), rt_const('HLE_BASE')
    mods = []
    for name in ORDER:
        path = exefs / name
        if not path.exists():
            continue
        n = Nso(str(path))
        mods.append((name, base, n.size, path))
        base = (base + n.size + 2 * ALIGN - 1) // ALIGN * ALIGN
    if not mods or mods[0][0] != 'main':
        sys.exit(f'{exefs}: no main module')
    if base > hi:
        sys.exit(f'{exefs}: the modules need {base - mods[0][1]:#x} bytes, more than the {hi - mods[0][1]:#x} '
                 'before HLE_BASE (runtime/rt.h)')
    return mods


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('game_dir')
    ap.add_argument('outdir')
    ap.add_argument('--simd', choices=('asm', 'c'),
                    default='asm' if platform.machine().lower() in ('arm64', 'aarch64') else 'c')
    ap.add_argument('-j', type=int, default=os.cpu_count() or 4)
    args = ap.parse_args()
    exefs = Path(args.game_dir).resolve() / 'exefs'
    out = Path(args.outdir).resolve()
    out.mkdir(parents=True, exist_ok=True)
    t0 = time.time()
    mods = layout(exefs)
    main_nso = Nso(str(exefs / 'main'))
    profile = games.select_build_id(main_nso.build_id)
    for name, base, size, _ in mods:
        print(f'{name:8} {base:#x} size {size:#x}', file=sys.stderr)

    def gen(mod):
        name, base, _, path = mod
        cmd = [sys.executable, str(ROOT / 'tools/gen.py'), name, str(path), hex(base), str(out / name),
               '--main', str(exefs / 'main'), '--simd', args.simd]
        if name == 'sdk':  # (the SDK functions the runtime implements itself: runtime/hle/hle_symbols.txt)
            cmd += ['--hle', str(ROOT / 'runtime/hle/hle_symbols.txt')]
        r = subprocess.run(cmd, cwd=ROOT / 'tools', capture_output=True, text=True)
        log = [l for l in r.stderr.splitlines() if 'progress' not in l]
        return name, r.returncode, '\n'.join(log)

    # (main is by far the largest: it starts first, the others share the rest of the machine with it)
    with ThreadPoolExecutor(max_workers=max(1, min(args.j, len(mods)))) as ex:
        for name, rc, log in ex.map(gen, mods):
            print(log, file=sys.stderr)
            if rc:
                sys.exit(f'{name}: the generator failed ({rc})')
    for d in out.iterdir():  # modules of other game files generated here before
        if d.is_dir() and d.name not in {m[0] for m in mods}:
            for f in d.iterdir():
                f.unlink()
            d.rmdir()

    lines = ['// Generated by tools/gen_game.py: the modules of this game code library (runtime/gamelib.h).',
             '#include "gamelib.h"', '']
    for name, *_ in mods:
        lines.append(f'extern const uint64_t {name}_fn_addrs[], {name}_fn_count;')
        lines.append(f'extern const GuestFn {name}_fn_ptrs[];')
    lines.append('const GameLibModule gamelib_modules[] = {')
    for name, base, size, _ in mods:
        lines.append(f'    {{"{name}", {base:#x}ull, {size:#x}ull, {name}_fn_addrs, {name}_fn_ptrs, &{name}_fn_count}},')
    lines.append('};')
    lines.append(f'const uint32_t gamelib_nmodules = {len(mods)};')
    text = '\n'.join(lines) + '\n'
    p = out / 'gamelib_modules.c'
    if not p.exists() or p.read_text() != text:
        p.write_text(text)
    bid = main_nso.build_id.upper().ljust(40, '0')[:40]
    (out / 'main_build_id.txt').write_text(bid + '\n')
    (out / 'game.txt').write_text((f'{profile.id} {profile.name}' if profile else 'none') + '\n')
    print(f'{profile.name if profile else "no profile"}: {len(mods)} modules generated in {time.time() - t0:.0f}s',
          file=sys.stderr)


if __name__ == '__main__':
    main()
